/// <reference types="node" />
/// <reference lib="es2023" />
// Генерує *.module.d.css.ts поруч із CSS-модулями, щоб styles.foo мав точний тип
// (strict TS: noPropertyAccessFromIndexSignature). Запуск: npm run css:types [-- --check]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const check = process.argv.includes('--check');
const root = new URL('../src', import.meta.url).pathname;
/** @type {string[]} */
const stale = [];

/** @param {string} dir */
function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (entry.name.endsWith('.module.css')) generate(path);
  }
}

/** @param {string} cssPath */
function generate(cssPath) {
  const css = readFileSync(cssPath, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  /** @type {Set<string>} */
  const names = new Set();
  for (const match of css.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) names.add(match[1]);
  const keys = [...names].toSorted((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const body = keys.map((name) => `  readonly ${JSON.stringify(name)}: string;`).join('\n');
  const content = `// Generated by scripts/css-module-types.mjs, do not edit\ndeclare const styles: {\n${body}\n};\nexport default styles;\n`;
  const dtsPath = cssPath.replace(/\.css$/, '.d.css.ts');
  if (existsSync(dtsPath) && readFileSync(dtsPath, 'utf8') === content) return;
  if (check) stale.push(dtsPath);
  else writeFileSync(dtsPath, content);
}

walk(root);
if (stale.length > 0) {
  // oxlint-disable-next-line no-console -- CLI-скрипт: повідомлення для розробника
  console.error(`Outdated CSS module types, run npm run css:types:\n${stale.join('\n')}`);
  process.exit(1);
}
